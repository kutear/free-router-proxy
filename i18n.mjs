// Language content for the web UI, decoupled from UI logic (ui.mjs)
// and server logic (server.mjs).
//
// To add a language: append [code, label] to LANGS and a matching dict to
// STRINGS. Every key present in `en` must exist in the new dict; missing
// keys fall back to English at runtime (see translate).
//
// Placeholders like {name} are filled by the caller. Values may contain
// simple <span class='mono'> markup; nothing else.

export const LANGS = [
  ['en', 'English'],
  ['zh-CN', '简体中文'],
  ['zh-TW', '繁體中文'],
  ['ja', '日本語'],
  ['ko', '한국어'],
  ['es', 'Español'],
  ['fr', 'Français'],
  ['de', 'Deutsch'],
  ['ru', 'Русский'],
  ['pt', 'Português'],
  ['it', 'Italiano'],
  ['ar', 'العربية'],
];

// Browser language tag -> supported code. `zh-HK` reads Traditional.
export function normalizeLang(tag) {
  const normalized = String(tag || '').toLowerCase().replace('_', '-');
  if (!normalized) return 'en';
  for (const [code] of LANGS) {
    if (code.toLowerCase() === normalized) return code;
  }
  if (normalized === 'zh-hk' || normalized === 'zh-hant' || normalized === 'zh-tw') return 'zh-TW';
  if (normalized.startsWith('zh')) return 'zh-CN';
  const prefix = normalized.split('-')[0];
  const hit = LANGS.find(([code]) => code.toLowerCase() === prefix);
  return hit ? hit[0] : 'en';
}

export function isSupportedLang(code) {
  return LANGS.some(([entry]) => entry === code);
}

// Pure lookup with English fallback and {var} interpolation. Shared
// semantics with the browser runtime in ui.mjs (which duplicates this tiny
// function to avoid shipping module loaders to the page).
export function translate(strings, lang, key, vars) {
  const value = strings?.[lang]?.[key] ?? strings?.en?.[key] ?? key;
  if (!vars) return value;
  return String(value).replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined || vars[name] === null ? '' : String(vars[name]),
  );
}

